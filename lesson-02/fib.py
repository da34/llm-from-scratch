"""斐波那契数列示例：打印数列的前 10 项。"""


def fib(n):
    """生成斐波那契数列的前 n 项。

    数列从 1, 1 开始，之后每一项都是前两项之和：1, 1, 2, 3, 5, 8, ...

    参数:
        n (int): 需要生成的项数。

    返回:
        list[int]: 长度恰好为 n 的斐波那契数列；当 n <= 0 时返回空列表。
    """
    seq = []
    a, b = 1, 1  # a: 当前项；b: 下一项
    for _ in range(n):
        seq.append(a)  # 把当前项加入结果
        a, b = b, a + b  # 窗口右移：a 变为下一项，b 变为前两项之和
    return seq


if __name__ == "__main__":
    print(fib(10))  # 打印数列的前 10 项
